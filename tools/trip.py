"""Generate prices.js (window.CAMP) and trip.js (window.TRIP) from trip.json + data/campsites.json.

trip.json is the one switch: the current trip (campsite, dates, registration settings) and the past ones.
The crawler (crawler/crawl.py) keeps data/campsites.json fresh; this turns the trip's campsite into the
shape calc.js, app.js, admin.js and the backend already read, so none of them changes.

    python tools/trip.py          # rewrite prices.js and trip.js
    python tools/trip.py --check  # exit 1 if either is stale (a gate)

--check ignores CAMP.checked (the crawl date), so it turns red only when something real changed, e.g. RTG's
prices. Then: run this, `python backend/build.py` (Code.gs carries prices.js), and the backend deploy (Yair's).
"""
import io, json, os, re, sys
from datetime import datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TRIP_JSON = os.path.join(ROOT, 'trip.json')
CAMPSITES_JSON = os.path.join(ROOT, 'data', 'campsites.json')
PRICES_JS = os.path.join(ROOT, 'prices.js')
TRIP_JS = os.path.join(ROOT, 'trip.js')

HEAD_PRICES = """// GENERATED by tools/trip.py from trip.json + data/campsites.json (the crawler's copy of parks.org.il). Do not edit.
// To change the trip, edit trip.json; prices come from the crawl. Then: python tools/trip.py, python backend/build.py,
// and the backend deploy: Code.gs carries a copy for the managing page's registration edits.
"""
HEAD_TRIP = """// GENERATED by tools/trip.py from trip.json. Do not edit. The campsite's details are in data/campsites.js.
"""

# Category wording (the 30/09/2026 hand-written prices.js). `rate` is the key in the crawled `rates`;
# a category whose rate the campsite does not list is left out. `ages`: 'adult' | 'child' | None.
CATEGORIES = [
    dict(id='adult', label='מבוגר', rate='adult', group='groupAdult', ages='adult', main=True),
    dict(id='child', label='ילד', rate='child', group='groupChild', ages='child', main=True),
    dict(id='toddler', label='פעוט', price=0, ages='toddler', main=True),
    dict(id='matmonAdult', label='מנוי מטמון — מבוגר', rate='matmonAdult', ages='adult',
         note='בהצגת כרטיס מנוי בתוקף, לפי ההרכב שעל הכרטיס'),
    dict(id='matmonChild', label='מנוי מטמון — ילד', rate='matmonChild', ages='child',
         note='בהצגת כרטיס מנוי בתוקף, לפי ההרכב שעל הכרטיס'),
    dict(id='reserveAdult', label='משרת מילואים פעיל ומשפחתו — מבוגר', rate='reserveAdult', ages='adult',
         note='לבעל הכרטיס ולבני משפחתו, בהצגת כרטיס מילואים פעיל'),
    dict(id='reserveChild', label='משרת מילואים פעיל ומשפחתו — ילד', rate='reserveChild', ages='child',
         note='לבעל הכרטיס ולבני משפחתו, בהצגת כרטיס מילואים פעיל'),
    dict(id='soldier', label='חייל/ת בשירות חובה / שירות לאומי', rate='soldier', note='בהצגת חוגר / כרטיס שירות לאומי'),
    dict(id='student', label='סטודנט/ית', rate='student', note='בהצגת כרטיס בתוקף'),
    dict(id='senior', label='אזרח/ית ותיק/ה', rate='senior', note='בהצגת תעודה'),
    dict(id='idfDisabled', label='נכה צה"ל ומלווה', rate='idfDisabled', note='בהצגת תעודה'),
    dict(id='escort', label='מלווה לאדם עם מוגבלות', price=0, note='פטור למלווה בלבד — בעל התעודה משלם מחיר מלא'),
]
MATTRESS_NOTE = 'לפי המלאי בחניון, ללא התחייבות'


def load(path):
    with io.open(path, encoding='utf-8') as f:
        return json.load(f)


def age_bounds(ages):
    """('גיל 14 ומעלה', 'מגיל 5 ועד 14') -> (14, 5). Either may be None when the price list has no age text."""
    adult = re.search(r'(\d+)\s*ומעלה', (ages or {}).get('adult') or '')
    child = re.search(r'(\d+)\D+?(\d+)', (ages or {}).get('child') or '')
    a = int(adult.group(1)) if adult else (int(child.group(2)) if child else None)
    c = int(child.group(1)) if child else None
    return a, c


def categories(site, group_min):
    rates = site.get('rates') or {}
    a, c = age_bounds(site.get('ages'))
    ages_txt = {
        'adult': f'גיל {a} ומעלה' if a else None,
        'child': f'גיל {c} עד {a - 1}' if a and c else None,
        'toddler': f'עד גיל {c}' if c else None,
    }
    out = []
    for t in CATEGORIES:
        price = t['price'] if 'price' in t else rates.get(t['rate'])
        if price is None:
            continue
        cat = {'id': t['id'], 'label': t['label']}
        ages = ages_txt.get(t.get('ages'))
        if ages:
            cat['ages'] = ages
        cat['price'] = price
        group = rates.get(t['group']) if t.get('group') else None
        if group is not None:
            cat['groupPrice'] = group
        if t.get('main'):
            cat['main'] = True
        note = t.get('note')
        if t['id'] == 'adult':
            note = (f'מגיל {a} ומעלה משלמים מחיר מבוגר.' if a else '') + \
                   (f' בקבוצה של {group_min}+ לנים: {group} ₪' if group is not None else '')
        elif t['id'] == 'child':
            note = (f'מגיל {c} ועד {a} (לא כולל).' if a and c else '') + \
                   (f' בקבוצה של {group_min}+ לנים: {group} ₪' if group is not None else '')
        elif t['id'] == 'toddler':
            note = f'ילדים מתחת לגיל {c} לא מופיעים במחירון ולא משלמים' if c else 'פעוטות לא מופיעים במחירון ולא משלמים'
        if note and note.strip():
            cat['note'] = note.strip()
        out.append(cat)
    return out


def extras(site):
    out = []
    for r in site.get('rentals') or []:
        if 'מזרן' in r.get('label', '') and r.get('price') is not None:
            out.append({'id': 'mattress', 'label': 'השכרת מזרן', 'unit': 'ללילה', 'price': r['price'], 'note': MATTRESS_NOTE})
            break
    return out


def day_first(iso):
    return datetime.fromisoformat(iso).strftime('%d/%m/%Y') if iso else ''


def build(trip, campsites):
    """-> (camp dict, trip dict). Raises SystemExit when the trip's campsite is not in the crawl."""
    site = next((c for c in campsites['campsites'] if c['id'] == trip['campsiteId']), None)
    if site is None:
        sys.exit(f"trip.json: campsite {trip['campsiteId']} is not in data/campsites.json - run the crawler")
    camp = {
        'tripId': trip['id'],
        'campsiteId': site['id'],
        'name': site['shortName'],
        'checked': day_first(site.get('checkedAt') or campsites.get('checkedAt')),
        'sourceUrl': site['url'],
        # Registration backend (Google Apps Script web-app URL, see backend/SETUP.md). Empty = registration off.
        'apiUrl': trip.get('apiUrl', ''),
        'defaultFrom': trip['from'],
        'defaultTo': trip['to'],
        # the trip's own days (activities may fall on them); the calculator's default stay is defaultFrom/To
        'tripFrom': trip['from'],
        'tripTo': trip['to'],
        'dateRangeStart': trip['dateRangeStart'],
        'dateRangeEnd': trip['dateRangeEnd'],
        'maxConsecutiveNights': trip['maxConsecutiveNights'],
        'groupMinPeople': trip['groupMinPeople'],
        'categories': categories(site, trip['groupMinPeople']),
        'extras': extras(site),
    }
    return camp, trip


def render(var, head, obj):
    return head + '\nwindow.' + var + ' = ' + json.dumps(obj, ensure_ascii=False, indent=2) + ';\n'


def read(path):
    try:
        with io.open(path, encoding='utf-8', newline='') as f:
            return f.read().replace('\r\n', '\n')
    except FileNotFoundError:
        return None


def parse_js(text):
    """The object a generated file assigns (None if it is not a generated file)."""
    m = re.search(r'^window\.\w+ = (\{.*\});\s*$', text or '', re.S | re.M)
    try:
        return json.loads(m.group(1)) if m else None
    except ValueError:
        return None


def main(argv):
    camp, trip = build(load(TRIP_JSON), load(CAMPSITES_JSON))
    outputs = [(PRICES_JS, render('CAMP', HEAD_PRICES, camp), camp), (TRIP_JS, render('TRIP', HEAD_TRIP, trip), trip)]
    if '--check' in argv:
        stale = []
        for path, _, obj in outputs:
            have = parse_js(read(path))
            if have is None or {**have, 'checked': None} != {**obj, 'checked': None}:
                stale.append(os.path.basename(path))
        if stale:
            sys.exit(', '.join(stale) + ' out of date with trip.json / data/campsites.json - run: python tools/trip.py, '
                     'then python backend/build.py (and the backend deploy)')
        print('prices.js and trip.js up to date')
        return
    for path, text, _ in outputs:
        if read(path) != text:
            with io.open(path, 'w', encoding='utf-8', newline='\n') as f:
                f.write(text)
            print('wrote', os.path.basename(path))


if __name__ == '__main__':
    main(sys.argv[1:])
